#!/usr/bin/env bash

# Canonical JetPack/L4T pairs supported by this repository. JetPack 5.1.5
# shipped with two BSP revisions; the JetPack shorthand selects the newer one.
DEFAULT_JETPACK_VERSION=6.1

resolve_jetson_version() {
  local requested=${1:-$DEFAULT_JETPACK_VERSION}
  JETPACK_VERSION=
  L4T_VERSION=

  case "$requested" in
    5.0.2) JETPACK_VERSION=5.0.2; L4T_VERSION=35.1.0 ;;
    5.1) JETPACK_VERSION=5.1; L4T_VERSION=35.2.1 ;;
    5.1.1) JETPACK_VERSION=5.1.1; L4T_VERSION=35.3.1 ;;
    5.1.2) JETPACK_VERSION=5.1.2; L4T_VERSION=35.4.1 ;;
    5.1.3) JETPACK_VERSION=5.1.3; L4T_VERSION=35.5.0 ;;
    5.1.4) JETPACK_VERSION=5.1.4; L4T_VERSION=35.6.0 ;;
    5.1.5) JETPACK_VERSION=5.1.5; L4T_VERSION=35.6.2 ;;
    5.1.6) JETPACK_VERSION=5.1.6; L4T_VERSION=35.6.4 ;;
    5.1.7) JETPACK_VERSION=5.1.7; L4T_VERSION=35.6.5 ;;
    6.0) JETPACK_VERSION=6.0; L4T_VERSION=36.3.0 ;;
    6.1) JETPACK_VERSION=6.1; L4T_VERSION=36.4.0 ;;
    6.2) JETPACK_VERSION=6.2; L4T_VERSION=36.4.3 ;;
    6.2.1) JETPACK_VERSION=6.2.1; L4T_VERSION=36.4.4 ;;
    6.2.2) JETPACK_VERSION=6.2.2; L4T_VERSION=36.5.0 ;;
    6.2.3) JETPACK_VERSION=6.2.3; L4T_VERSION=36.5.2 ;;

    35.1|35.1.0) JETPACK_VERSION=5.0.2; L4T_VERSION=35.1.0 ;;
    35.2.1) JETPACK_VERSION=5.1; L4T_VERSION=35.2.1 ;;
    35.3.1) JETPACK_VERSION=5.1.1; L4T_VERSION=35.3.1 ;;
    35.4.1) JETPACK_VERSION=5.1.2; L4T_VERSION=35.4.1 ;;
    35.5.0) JETPACK_VERSION=5.1.3; L4T_VERSION=35.5.0 ;;
    35.6.0) JETPACK_VERSION=5.1.4; L4T_VERSION=35.6.0 ;;
    35.6.1|35.6.2) JETPACK_VERSION=5.1.5; L4T_VERSION=$requested ;;
    35.6.4) JETPACK_VERSION=5.1.6; L4T_VERSION=35.6.4 ;;
    35.6.5) JETPACK_VERSION=5.1.7; L4T_VERSION=35.6.5 ;;
    36.3|36.3.0) JETPACK_VERSION=6.0; L4T_VERSION=36.3.0 ;;
    36.4|36.4.0) JETPACK_VERSION=6.1; L4T_VERSION=36.4.0 ;;
    36.4.3) JETPACK_VERSION=6.2; L4T_VERSION=36.4.3 ;;
    36.4.4) JETPACK_VERSION=6.2.1; L4T_VERSION=36.4.4 ;;
    36.5.0) JETPACK_VERSION=6.2.2; L4T_VERSION=36.5.0 ;;
    36.5.2) JETPACK_VERSION=6.2.3; L4T_VERSION=36.5.2 ;;
    35.*|36.*)
      [[ $requested =~ ^(35|36)\.[0-9]+\.[0-9]+$ ]] || return 1
      L4T_VERSION=$requested
      ;;
    *) return 1 ;;
  esac

  if [[ -n $JETPACK_VERSION ]]; then
    JETSON_VERSION_SLUG="jp${JETPACK_VERSION}-l4t${L4T_VERSION}"
  else
    JETSON_VERSION_SLUG="l4t${L4T_VERSION}"
  fi
}
